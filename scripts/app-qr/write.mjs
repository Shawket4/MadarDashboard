// Writes shared/apps-qr.ts and shared/apps/qr/<app>-<lang>.svg: each app's downloads
// page (shared/apps.ts `downloadsHref`) as a QR code, so a tablet's camera opens it from
// the dashboard on a laptop. Encoded by the Rust `qrcode` crate (the one MadarRust uses);
// run after a downloads URL changes:  node scripts/app-qr/write.mjs
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { APP_KEYS, downloadsHref } from "../../shared/apps.ts";

const here = dirname(fileURLToPath(import.meta.url));
const shared = join(here, "../../shared");
const langs = ["en", "ar"];
const urls = APP_KEYS.flatMap((app) => langs.map((lang) => ({ app, lang, url: downloadsHref(lang, app) })));

const out = execFileSync("cargo", ["run", "-q", "--release", "--manifest-path", join(here, "Cargo.toml"), "--", ...urls.map((u) => u.url)], {
  encoding: "utf8",
}).trim().split("\n");

const codes = {};
mkdirSync(join(shared, "apps/qr"), { recursive: true });
urls.forEach(({ app, lang, url }, i) => {
  const [size, d] = [Number(out[i].split(" ")[0]), out[i].slice(out[i].indexOf(" ") + 1)];
  (codes[app] ??= {})[lang] = { url, size, d };
  writeFileSync(
    join(shared, `apps/qr/${app}-${lang}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-2 -2 ${size + 4} ${size + 4}" shape-rendering="crispEdges"><path d="${d}" fill="#000"/></svg>\n`,
  );
});

writeFileSync(
  join(shared, "apps-qr.ts"),
  `// Generated by scripts/app-qr/write.mjs from shared/apps.ts. Do not edit.\n` +
    `import type { AppKey } from "./apps";\n\n` +
    `/** A QR code: \`size\` modules square, the dark ones as one SVG path, no quiet zone. */\n` +
    `export interface AppQr { url: string; size: number; d: string }\n\n` +
    `export const APP_QR: Record<AppKey, Record<"en" | "ar", AppQr>> = ${JSON.stringify(codes, null, 2)};\n`,
);
console.log(`wrote ${urls.length} codes`);
